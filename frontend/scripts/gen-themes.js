// Generates src/themes.css: Tailwind's palettes as CSS variables, remapped
// per theme. Run after changing a mapping:  node scripts/gen-themes.js
//
// The app is styled with Tailwind's slate / cyan / amber ... classes. Each of
// those classes reads rgb(var(--tw-<family>-<shade>)), so a theme swaps the
// whole look by redefining the variables, without touching components.
const fs = require("fs");
const path = require("path");
const colors = require("tailwindcss/colors");

const FAMILIES = ["slate", "cyan", "amber", "red", "green", "purple", "emerald", "blue", "orange", "rose", "yellow", "sky", "teal", "indigo", "pink", "lime", "gray", "zinc"];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

const rgb = (hex) => {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(" ");
};

// Sunlight: light background, near-black text. Neutrals invert, leaning dark
// for text (slate-400 muted text -> slate-700). Accents keep their hue but
// light text shades become deep ones (cyan-300 -> cyan-800) so they read on
// white in glare; dark tint backgrounds become pale tints.
const SUN_NEUTRAL = { 50: 950, 100: 900, 200: 800, 300: 800, 400: 700, 500: 600, 600: 600, 700: 300, 800: 200, 900: 100, 950: "white" };
const SUN_ACCENT = { 50: 950, 100: 900, 200: 900, 300: 800, 400: 700, 500: 600, 600: 600, 700: 200, 800: 100, 900: 100, 950: 50 };

const NEUTRALS = new Set(["slate", "gray", "zinc"]);

function block(selector, value) {
  const lines = [];
  for (const f of FAMILIES) {
    for (const s of SHADES) lines.push(`  --tw-${f}-${s}: ${value(f, s)};`);
  }
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

const base = block(":root", (f, s) => rgb(colors[f][s]));
const sun = block('html[data-theme="sun"]', (f, s) => {
  const m = (NEUTRALS.has(f) ? SUN_NEUTRAL : SUN_ACCENT)[s];
  return m === "white" ? "255 255 255" : rgb(colors[f][m]);
});

const out = `/* GENERATED by scripts/gen-themes.js - edit the script, not this file. */
${base}
:root {
  --tw-white: 255 255 255;
  --tw-black: 0 0 0;
}

${sun}
html[data-theme="sun"] {
  --tw-white: 2 6 23;
  --background: 0 0% 100%;
  --foreground: 222 84% 5%;
  --card: 210 40% 98%;
  --card-foreground: 222 84% 5%;
  --popover: 0 0% 100%;
  --popover-foreground: 222 84% 5%;
  --primary: 192 91% 30%;
  --primary-foreground: 0 0% 100%;
  --secondary: 221 83% 40%;
  --secondary-foreground: 0 0% 100%;
  --muted: 214 32% 91%;
  --muted-foreground: 215 25% 27%;
  --accent: 32 95% 40%;
  --accent-foreground: 0 0% 100%;
  --destructive: 0 74% 42%;
  --destructive-foreground: 0 0% 100%;
  --border: 215 20% 65%;
  --input: 215 20% 65%;
  --ring: 192 91% 30%;
  color-scheme: light;
}
`;

fs.writeFileSync(path.join(__dirname, "..", "src", "themes.css"), out);
console.log("wrote src/themes.css");
